-- Student Organizer: Supabase PostgreSQL schema
-- Run this whole script once in Supabase Dashboard -> SQL Editor.
-- Authentication is managed by Supabase Auth; never store user passwords in public tables.

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = timezone('utc', now()); return new; end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name varchar(100) not null default 'Student' check (char_length(trim(full_name)) >= 2),
  email varchar(255) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  theme text not null default 'light' check (theme in ('light','dark')),
  notify_deadlines boolean not null default true,
  notify_exams boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name varchar(100) not null,
  color char(7) not null default '#79d1ae' check (color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, name),
  unique(id, user_id)
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint null references public.subjects(id) on delete set null,
  title varchar(200) not null,
  description text,
  due_date date not null,
  due_time time,
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  status text not null default 'todo' check (status in ('todo','in_progress','done')),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_tasks_user_due on public.tasks(user_id,due_date);
create index if not exists idx_tasks_user_status on public.tasks(user_id,status);

create table if not exists public.timetable_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  teacher varchar(120), classroom varchar(60),
  day_of_week smallint not null check(day_of_week between 1 and 7),
  start_time time not null, end_time time not null check(end_time > start_time),
  color char(7), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_tt_user_day on public.timetable_entries(user_id,day_of_week,start_time);

create table if not exists public.calendar_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title varchar(200) not null, description text, event_date date not null,
  start_time time, end_time time,
  color char(7) not null default '#f6a55b',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check(start_time is null or end_time is null or end_time > start_time)
);
create index if not exists idx_events_user_date on public.calendar_events(user_id,event_date);

create table if not exists public.grades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  title varchar(200) not null,
  score numeric(7,2) not null,
  max_score numeric(7,2) not null check(max_score > 0),
  assessed_on date not null, comment varchar(1000),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check(score >= 0 and score <= max_score)
);
create index if not exists idx_grades_user_subject on public.grades(user_id,subject_id);
create index if not exists idx_grades_user_date on public.grades(user_id,assessed_on);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint null references public.subjects(id) on delete set null,
  title varchar(200) not null, content text,
  is_pinned boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_notes_user_created on public.notes(user_id,created_at desc);

create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint null references public.subjects(id) on delete set null,
  title varchar(200) not null,
  type text not null default 'exam' check(type in ('exam','test','project','presentation','assignment')),
  exam_date date not null, exam_time time, description text,
  prep_status text not null default 'not_started' check(prep_status in ('not_started','in_progress','ready')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_exams_user_date on public.exams(user_id,exam_date);

create table if not exists public.study_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint null references public.subjects(id) on delete set null,
  title varchar(200) not null, description text, target_date date not null,
  target_minutes integer not null check(target_minutes > 0),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(id,user_id)
);

create table if not exists public.study_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_id bigint not null references public.study_goals(id) on delete cascade,
  title varchar(200), session_date date not null,
  duration_minutes integer not null check(duration_minutes between 1 and 1440),
  is_completed boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_sessions_user_date on public.study_sessions(user_id,session_date);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null check(type in ('task_due','task_overdue','exam_upcoming')),
  ref_key varchar(60) not null, ref_id bigint not null,
  title varchar(200) not null, message varchar(500) not null, due_at timestamptz not null,
  is_read boolean not null default false, is_dismissed boolean not null default false,
  created_at timestamptz not null default now(),
  unique(user_id,ref_key)
);
create index if not exists idx_notifications_user_state on public.notifications(user_id,is_dismissed,is_read);

-- Keep profile/settings in sync when a new Supabase Auth account is created.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id,full_name,email)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'),''),'Student'), coalesce(new.email,''))
  on conflict (id) do update set email = excluded.email;
  insert into public.user_settings(user_id) values(new.id) on conflict(user_id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Backfill profile/settings rows if this script is run after accounts already exist.
insert into public.profiles(id,full_name,email)
select id, coalesce(nullif(trim(raw_user_meta_data ->> 'full_name'),''),'Student'), coalesce(email,'')
from auth.users on conflict (id) do update set email = excluded.email;
insert into public.user_settings(user_id) select id from auth.users on conflict(user_id) do nothing;

-- Automatically update updated_at fields.
do $$
declare t text;
begin
  foreach t in array array['profiles','user_settings','subjects','tasks','timetable_entries','calendar_events','grades','notes','exams','study_goals','study_sessions'] loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute procedure public.set_updated_at()', t);
  end loop;
end $$;

-- Enable Row Level Security on every table exposed through the Data API.
alter table public.profiles enable row level security;
alter table public.user_settings enable row level security;
alter table public.subjects enable row level security;
alter table public.tasks enable row level security;
alter table public.timetable_entries enable row level security;
alter table public.calendar_events enable row level security;
alter table public.grades enable row level security;
alter table public.notes enable row level security;
alter table public.exams enable row level security;
alter table public.study_goals enable row level security;
alter table public.study_sessions enable row level security;
alter table public.notifications enable row level security;

drop policy if exists "profile own select" on public.profiles;
create policy "profile own select" on public.profiles for select to authenticated using (id = (select auth.uid()));
drop policy if exists "profile own update" on public.profiles;
create policy "profile own update" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
drop policy if exists "settings own access" on public.user_settings;
create policy "settings own access" on public.user_settings for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

do $$
declare t text;
begin
  foreach t in array array['subjects','tasks','timetable_entries','calendar_events','grades','notes','exams','study_goals','study_sessions','notifications'] loop
    execute format('drop policy if exists "user owns rows" on public.%I', t);
    execute format('create policy "user owns rows" on public.%I for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))', t);
  end loop;
end $$;

grant usage on schema public to authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
